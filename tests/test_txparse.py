@pytest.mark.parametrize('title,text,tx_type,amount,merchant,dt', CASES)
def test_formats(title, text, tx_type, amount, merchant, dt):
    r = parse_notification(title, text, NOW)
    assert r is not None
    assert (r['tx_type'], r['amount'], r['title']) == (tx_type, amount, merchant)
    if dt:
        assert r['datetime'] == dt


