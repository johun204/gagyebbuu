def test_foreign_currency_needs_amount_input():
    r = parse_notification('신한카드', '[Web발신]\n신한카드(1*2*)해외승인 홍*동 USD 12.99 11/06 03:12 NETFLIX.COM', NOW)
    assert (r['tx_type'], r['amount'], r['title']) == ('지출', 0, 'NETFLIX.COM (USD 12.99)')
    assert r['datetime'] == D(11, 6, 3, 12)


def test_points_and_balance_not_taken_as_amount():
    r = parse_notification('', '스타벅스 6,500원 결제, 포인트 65원 적립 (잔액 3,000원)', NOW)
    assert (r['amount'], r['title']) == (6500, '스타벅스')


def test_year_rollover_and_after_midnight():
    r = parse_notification('', '우리카드 승인 9,900원 12/31 23:50 넷플릭스', datetime(2027, 1, 1, 0, 5))
    assert r['datetime'] == datetime(2026, 12, 31, 23, 50)
    r = parse_notification('', '체크승인 3,000원 23:55 편의점', datetime(2026, 11, 7, 0, 2))
    assert r['datetime'] == datetime(2026, 11, 6, 23, 55)


def test_no_date_uses_posted_time():
    r = parse_notification('네이버페이', '8,900원 결제', NOW)
    assert r['datetime'] == NOW
